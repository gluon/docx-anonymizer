RESIDUE_COMMENT = "<!-- relu par Sylvie Marchand -->"


def build_with_residue(path) -> Path:
    """Same document, with a name in a place no substitution pass reaches.

    An XML comment is not a run, not an attribute we rewrite, not a field.
    Word never writes one, but other tools in a document's life do, and it
    stands in here for the general case: something the engine cannot clean.
    The point of the fixture is that the export refuses rather than ships.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, data in PARTS:
            if name == "word/document.xml":
                data = data.replace(b"<w:body>", RESIDUE_COMMENT.encode() + b"<w:body>")
            info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 12, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, data)
    return path
